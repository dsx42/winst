#Requires -Version 5.1

function Get-WinstVersionPatterns {
    # 键的顺序也是未指定识别器时的尝试顺序。
    return [ordered]@{
        semver = '(?<![0-9.])(?:[vV])?(?<v>[0-9]+(?:\.[0-9]+){1,3})(?![0-9]|\.[0-9])'
        date = '(?<![0-9])(?<v>[0-9]{4}[-.][0-9]{2}[-.][0-9]{2}|[0-9]{8})(?![0-9])'
        digits = '(?<![0-9])(?<v>[0-9]{2,})(?![0-9])'
    }
}
